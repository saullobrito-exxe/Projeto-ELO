/**
 * Função real de varredura recursiva do Google Drive v3
 * Executa chamadas com paginação e suporte a rate-limit
 */
export async function fetchLiveDriveFiles(folderId: string, accessToken: string) {
  const files: any[] = [];
  let pageToken: string | null = null;

  do {
    const params = new URLSearchParams({
      q: `'${folderId}' in parents and trashed = false`,
      fields: 'nextPageToken, files(id, name, mimeType, size, createdTime, modifiedTime, webViewLink, thumbnailLink, parents)',
      pageSize: '100',
    });

    if (pageToken) {
      params.set('pageToken', pageToken);
    }

    const response = await fetch(`https://www.googleapis.com/drive/v3/files?${params.toString()}`, {
      headers: {
        Authorization: `Bearer ${accessToken}`,
      },
    });

    if (!response.ok) {
      const errBody = await response.text();
      throw new Error(`Erro na Drive API (${response.status}): ${errBody}`);
    }

    const data = await response.json();
    if (data.files && Array.isArray(data.files)) {
      files.push(...data.files);
    }
    pageToken = data.nextPageToken || null;
  } while (pageToken);

  return files;
}
